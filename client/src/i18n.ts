/**
 * English / Brazilian Portuguese UI strings. The language is picked once at load (saved choice,
 * else the browser language) and changing it reloads the page, since the UI is built at startup.
 * Keys are the English table's; the Portuguese table must cover every one of them (type-checked).
 */

export type Lang = 'en' | 'pt';
export const LANGS: readonly Lang[] = ['en', 'pt'];
export const LANG_KEY = 'byte_grounds.lang';

/** A saved choice wins; else Portuguese for a `pt*` browser language; else English. */
export function detectLang(saved: string | null | undefined, navLang: string | undefined): Lang {
  if (saved === 'en' || saved === 'pt') return saved;
  return navLang?.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

