export const MESSAGES: Record<Lang, Record<MsgKey, string>> = { en, pt };

function storedLang(): string | null {
  try {
    return localStorage.getItem(LANG_KEY);
  } catch {
    return null;
  }
}

/** Resolved once: browsers detect; tests and other non-window hosts stay English. */
export const lang: Lang = typeof window === 'undefined' ? 'en' : detectLang(storedLang(), navigator.language);

/** Fill `{name}` placeholders from `vars` (unknown ones stay as written). */
export function format(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** The UI string for `key` in a language (English by default fallback), placeholders filled. */
export function translate(l: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  return format(MESSAGES[l][key] || en[key], vars);
}

/** The UI string for `key` in the current language. */
export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  return translate(lang, key, vars);
}

/** Save a language and reload, so every screen is rebuilt in it. */
export function setLang(l: Lang): void {
  try {
    localStorage.setItem(LANG_KEY, l);
  } catch {
    // private mode: the reload still detects from the browser
  }
  location.reload();
}

/** A small EN / PT selector bound to `setLang`. */
export function langSwitch(): HTMLSelectElement {
  const sel = document.createElement('select');
  sel.className = 'lang-switch';
  sel.setAttribute('aria-label', 'Language / Idioma');
  for (const l of LANGS) sel.add(new Option(l === 'en' ? 'EN' : 'PT', l, false, l === lang));
  sel.addEventListener('change', () => setLang(sel.value as Lang));
  return sel;
}

/** Set the document language (for screen readers and the browser's spellcheck). */
export function applyDocLang(): void {
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
}
